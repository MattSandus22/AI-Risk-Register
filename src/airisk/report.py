def _treatment_note(r: Risk) -> str:
    if r.treatment == "accept" and r.acceptance:
        return _e(f"approved by {r.acceptance.approver}, expires {r.acceptance.expires}")
    if not r.treatments:
        return "no treatments"
    return f"{sum(t.implemented for t in r.treatments)}/{len(r.treatments)} implemented"


