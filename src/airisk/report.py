"""Build a report view of the register and render it as Markdown, HTML or CSV."""

from __future__ import annotations

import csv
import html
import io
from dataclasses import dataclass
from datetime import date

from . import __version__
from .coverage import COVERED, GAP, PLANNED, CoverageRow, iso_coverage, nist_coverage, summary
from .frameworks import CATEGORIES, EU_AI_ACT_TIERS
from .models import Register, Risk
from .validate import Issue


@dataclass
class RiskRow:
    risk: Risk
    system_name: str
    inherent_rating: str
    residual_rating: str
    above_appetite: bool
    next_review: date | None
    overdue: bool


@dataclass
class View:
    register: Register
    as_of: date
    issues: list[Issue]
    rows: list[RiskRow]
    nist: list[CoverageRow]
    iso: list[CoverageRow]

    @property
    def cfg(self):
        return self.register.config

    def stat(self, name: str) -> int:
        return {
            "systems": len(self.register.systems),
            "risks": len(self.rows),
            "above_appetite": sum(r.above_appetite for r in self.rows),
            "overdue": sum(r.overdue for r in self.rows),
            "errors": sum(i.level == "error" for i in self.issues),
            "warnings": sum(i.level == "warning" for i in self.issues),
        }[name]

    def heatmap(self, residual: bool) -> dict[tuple[int, int], list[str]]:
        grid: dict[tuple[int, int], list[str]] = {}
        for row in self.rows:
            r = row.risk
            key = (r.residual_likelihood, r.residual_impact) if residual else (r.likelihood, r.impact)
            grid.setdefault(key, []).append(r.id)
        return grid


def build_view(register: Register, issues: list[Issue], as_of: date) -> View:
    rows = []
    for r in register.risks:
        rows.append(RiskRow(
            risk=r,
            system_name=register.systems[r.system].name,
            inherent_rating=register.config.rating(r.inherent_score),
            residual_rating=register.config.rating(r.residual_score),
            above_appetite=register.above_appetite(r),
            next_review=register.next_review(r),
            overdue=register.review_overdue(r, as_of),
        ))
    rows.sort(key=lambda x: (-x.risk.residual_score, -x.risk.inherent_score, x.risk.id))
    return View(register, as_of, issues, rows, nist_coverage(register), iso_coverage(register))


# ---------------------------------------------------------------------------- CSV

def to_csv(view: View) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["risk_id", "system_id", "system", "title", "category", "owner",
                "likelihood", "impact", "inherent_score", "inherent_rating",
                "residual_likelihood", "residual_impact", "residual_score", "residual_rating",
                "above_appetite", "treatment", "implemented_treatments", "open_treatments",
                "last_reviewed", "next_review", "review_overdue"])
    for row in view.rows:
        r = row.risk
        w.writerow([r.id, r.system, row.system_name, r.title, CATEGORIES[r.category], r.owner,
                    r.likelihood, r.impact, r.inherent_score, row.inherent_rating,
                    r.residual_likelihood, r.residual_impact, r.residual_score, row.residual_rating,
                    "yes" if row.above_appetite else "no", r.treatment,
                    sum(t.implemented for t in r.treatments),
                    sum(not t.implemented for t in r.treatments),
                    r.last_reviewed or "", row.next_review or "", "yes" if row.overdue else "no"])
    return buf.getvalue()


# ----------------------------------------------------------------------- Markdown

def _md_heatmap(view: View, residual: bool) -> list[str]:
    grid = view.heatmap(residual)
    out = ["| Impact ↓ / Likelihood → | 1 | 2 | 3 | 4 | 5 |", "|---|---|---|---|---|---|"]
    for imp in range(5, 0, -1):
        cells = []
        for lik in range(1, 6):
            ids = grid.get((lik, imp), [])
            cells.append(", ".join(ids) if ids else "·")
        out.append(f"| **{imp}** | " + " | ".join(cells) + " |")
    return out


def to_markdown(view: View) -> str:
    cfg = view.cfg
    L: list[str] = []
    add = L.append
    add(f"# AI Risk Register: {cfg.organization}")
    add("")
    add(f"As of {view.as_of}. Risk appetite: residual score ≤ {cfg.risk_appetite}. "
        f"Generated by ai-risk-register v{__version__}.")
    add("")
    add("## Summary")
    add("")
    add("| AI systems | Risks | Above appetite | Reviews overdue | Validation findings |")
    add("|---|---|---|---|---|")
    add(f"| {view.stat('systems')} | {view.stat('risks')} | {view.stat('above_appetite')} | "
        f"{view.stat('overdue')} | {view.stat('errors')} errors, {view.stat('warnings')} warnings |")
    add("")

    add("## Risks by residual score")
    add("")
    add("| ID | System | Risk | Category | Inherent | Residual | Treatment | Next review |")
    add("|---|---|---|---|---|---|---|---|")
    for row in view.rows:
        r = row.risk
        flag = " ⚑" if row.above_appetite else ""
        review = f"{row.next_review or 'never reviewed'}" + (" (overdue)" if row.overdue else "")
        add(f"| {r.id} | {row.system_name} | {r.title} | {CATEGORIES[r.category]} | "
            f"{r.inherent_score} {row.inherent_rating} | {r.residual_score} {row.residual_rating}{flag} | "
            f"{r.treatment} | {review} |")
    add("")
    add("⚑ = residual score above risk appetite.")
    add("")

    add("## Heatmaps")
    add("")
    add("**Inherent**")
    add("")
    L.extend(_md_heatmap(view, residual=False))
    add("")
    add("**Residual**")
    add("")
    L.extend(_md_heatmap(view, residual=True))
    add("")

    add("## AI systems")
    add("")
    add("| ID | System | Stage | EU AI Act tier | Owner | Risks |")
    add("|---|---|---|---|---|---|")
    for s in view.register.systems.values():
        tier = EU_AI_ACT_TIERS.get(s.eu_ai_act_tier, "Not classified")
        add(f"| {s.id} | {s.name} | {s.lifecycle_stage} | {tier} | {s.owner} | {len(view.register.risks_for(s.id))} |")
    add("")

    for title, rows in (("NIST AI RMF coverage", view.nist), ("ISO/IEC 42001 Annex A coverage", view.iso)):
        s = summary(rows)
        add(f"## {title}")
        add("")
        add(f"{s[COVERED]} covered, {s[PLANNED]} planned only, {s[GAP]} gaps.")
        add("")
        add("| Ref | Description | Status | Implemented by | Planned |")
        add("|---|---|---|---|---|")
        for row in rows:
            add(f"| {row.ref} | {row.title} | {row.status} | {', '.join(row.implemented) or '—'} | "
                f"{', '.join(row.planned) or '—'} |")
        add("")

    add("## Validation findings")
    add("")
    if not view.issues:
        add("None.")
    for i in view.issues:
        add(f"- **{i.level}** `{i.ref}`: {i.message}")
    add("")
    return "\n".join(L)


# --------------------------------------------------------------------------- HTML

def _e(x) -> str:
    return html.escape(str(x))


def _band_class(view: View, score: int) -> str:
    return "b-" + view.cfg.rating(score).lower()


def _html_heatmap(view: View, residual: bool) -> str:
    grid = view.heatmap(residual)
    cells = []
    for imp in range(5, 0, -1):
        cells.append(f'<div class="axis">{imp}</div>')
        for lik in range(1, 6):
            ids = grid.get((lik, imp), [])
            score = lik * imp
            title = _e(", ".join(ids)) if ids else f"Score {score}"
            count = f'<span class="n">{len(ids)}</span>' if ids else ""
            cls = _band_class(view, score) + (" filled" if ids else "")
            cells.append(f'<div class="cell {cls}" title="{title}">{count}<span class="s">{score}</span></div>')
    cells.append('<div></div>' + "".join(f'<div class="axis">{n}</div>' for n in range(1, 6)))
    label = "Residual" if residual else "Inherent"
    return (f'<figure class="heat"><figcaption>{label}</figcaption>'
            f'<div class="grid">{"".join(cells)}</div>'
            f'<div class="axes"><span>↑ Impact</span><span>Likelihood →</span></div></figure>')


def _coverage_table(rows: list[CoverageRow]) -> str:
    s = summary(rows)
    body = "".join(
        f'<tr><td class="mono">{_e(r.ref)}</td><td>{_e(r.title)}</td>'
        f'<td><span class="pill c-{r.status.lower()}">{r.status}</span></td>'
        f'<td class="mono small">{_e(", ".join(r.implemented) or "—")}</td>'
        f'<td class="mono small">{_e(", ".join(r.planned) or "—")}</td></tr>'
        for r in rows
    )
    return (f'<p class="muted">{s[COVERED]} covered · {s[PLANNED]} planned only · {s[GAP]} gaps</p>'
            '<div class="scroll"><table><thead><tr><th>Ref</th><th>Description</th><th>Status</th>'
            f'<th>Implemented by</th><th>Planned</th></tr></thead><tbody>{body}</tbody></table></div>')


